export default function PixelArt({ rows, palette = PAL, px = 4, className = '', style = {} }) {
    const h = rows.length;
    const w = Math.max(...rows.map((r) => r.length));
    const rects = [];
    rows.forEach((row, y) => {
        [...row].forEach((ch, x) => {
            if (ch !== '.' && palette[ch]) {
                rects.push(
                    <rect key={`${x}-${y}`} x={x} y={y} width={1.02} height={1.02} fill={palette[ch]} />
                );
            }
        });
    });
    return (
        <svg
            className={`pixelated ${className}`}
            width={w * px}
            height={h * px}
            viewBox={`0 0 ${w} ${h}`}
            shapeRendering="crispEdges"
            xmlns="http://www.w3.org/2000/svg"
            style={style}
            aria-hidden="true"
        >
            {rects}
        </svg>
    );
}

function gridToSvg(rows, palette, scale) {
    const h = rows.length;
    const w = Math.max(...rows.map((r) => r.length));
    let rects = '';
    rows.forEach((row, y) => {
        [...row].forEach((ch, x) => {
            if (ch !== '.' && palette[ch]) {
                rects += `<rect x="${x}" y="${y}" width="1.02" height="1.02" fill="${palette[ch]}"/>`;
            }
        });
    });
    return `<svg xmlns="http://www.w3.org/2000/svg" width="${w * scale}" height="${h * scale}" viewBox="0 0 ${w} ${h}" shape-rendering="crispEdges">${rects}</svg>`;
}

export function installCursors() {
    const arrow = encodeURIComponent(gridToSvg(CURSOR_ARROW, PAL, 2));
    const hand = encodeURIComponent(gridToSvg(CURSOR_HAND, PAL, 2));
    const style = document.createElement('style');
    style.id = 'pixel-cursors';
    style.textContent = `
        html, body, #root, div, span, p, h1, h2, h3, h4, li, ul, header, section {
            cursor: url("data:image/svg+xml;utf8,${arrow}") 2 2, auto;
        }
        a, button, [role="button"], input, textarea, select, label, [data-clickable] {
            cursor: url("data:image/svg+xml;utf8,${hand}") 8 2, pointer !important;
        }
    `;
    document.head.appendChild(style);
}
